export function translateText(value: string): string {
  const exact = EXACT[value];
  if (exact !== undefined) return exact;
  const normalized = value.replace(/\s+/g, " ").trim();
  const normalizedExact = EXACT[normalized];
  if (normalizedExact !== undefined) return normalizedExact;
  for (const [pattern, replacement] of RULES) {
    if (pattern.test(normalized)) return normalized.replace(pattern, replacement);
  }
  return value;
}

export function hasTranslation(value: string): boolean {
  const exact = EXACT[value];
  if (exact !== undefined) return true;
  const normalized = value.replace(/\s+/g, " ").trim();
  const normalizedExact = EXACT[normalized];
  if (normalizedExact !== undefined) return true;
  return RULES.some(([pattern]) => pattern.test(normalized));
}
