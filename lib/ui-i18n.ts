const RULES: Array<[RegExp, string]> = [
  [/^当前账户：(.+)$/, "Current account: $1"],
  [/^Username (.+) · 注册于 (.+)$/, "Username $1 · Joined $2"],
  [/^· 最近活动 (.+)$/, "· Last active $1"],
  [/^用户名 (.+) · 注册于 (.+)$/, "Username $1 · Joined $2"],
  [/^(.+) · 最近活动 (.+)$/, "$1 · Last active $2"],
  [/^([0-9]+) 个$/, "$1"],
  [/^共\s*(\d+)\s*个用户$/, "$1 users"],
  [/^共\s*(\d+)\s*个账号$/, "$1 accounts"],
  [/^第三方登录\s+(.+)$/, "Third-party login $1"],
  [/^删除\s+(.+)\?$/, "Delete $1?"],
  [/^已接入\s*(\d+)\s*个应用$/, "$1 connected apps"],
];

export function translateText(value: string): string {
  const exact = EXACT[value];
  if (exact !== undefined) return exact;
  for (const [pattern, replacement] of RULES) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }
  return value;
}

export function hasTranslation(value: string): boolean {
  const exact = EXACT[value];
  if (exact !== undefined) return exact !== "";
  return RULES.some(([pattern]) => pattern.test(value));
}
