/**
 * Rules whose captured group is itself a UI label that needs translating
 * (server messages such as `${label} 不是合法 URL`). A plain string
 * replacement would leave the captured Chinese label in place.
 */
const DYNAMIC_RULES: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
  [/^(.+) 不是合法 URL$/, (m) => `${translateText(m[1])} is not a valid URL`],
  [/^(.+) 只支持 http\/https$/, (m) => `${translateText(m[1])} only supports http/https`],
  [/^(.+) 生产环境必须使用 https$/, (m) => `${translateText(m[1])} must use https in production`],
  [/^(.+) 不允许内网地址$/, (m) => `${translateText(m[1])} cannot use a private address`],
  [/^(.+) 域名无法解析$/, (m) => `Could not resolve the host for ${translateText(m[1])}`],
  [/^(.+) 解析到内网地址，已拒绝$/, (m) => `${translateText(m[1])} resolves to a private address and was rejected`],
  [/^(.+) 至少 (\d+) 个字符$/, (m) => `${translateText(m[1])} must be at least ${m[2]} characters`],
  [/^(.+) 不能超过 (\d+) 个字符$/, (m) => `${translateText(m[1])} must be at most ${m[2]} characters`],
  [/^内容不能超过 (\d+) 个字符$/, (m) => `Content must be at most ${m[1]} characters`],
  [/^(.+)必须通过 HTTPS 加密提交$/, (m) => `${translateText(m[1])} must be submitted encrypted over HTTPS`],
];

export function translateText(value: string): string {
  const exact = EXACT[value];
  if (exact !== undefined) return exact;
  const normalized = value.replace(/\s+/g, " ").trim();
  const normalizedExact = EXACT[normalized];
  if (normalizedExact !== undefined) return normalizedExact;
  for (const [pattern, build] of DYNAMIC_RULES) {
    const match = value.match(pattern);
    if (match) return build(match);
  }
  for (const [pattern, replacement] of RULES) {
    if (pattern.test(value)) return value.replace(pattern, replacement);
  }
  // Lists (risk reasons, scopes, ...) are joined with a Chinese semicolon before
  // they reach the DOM. Translate each segment so the joined value ends up
  // English too.
  if (value.includes("；")) {
    const parts = value.split("；").map((part) => part.trim()).filter(Boolean);
    if (parts.length > 1 && parts.some((part) => hasTranslation(part))) {
      return parts.map((part) => (hasTranslation(part) ? translateText(part) : part)).join("; ");
    }
  }
  return value;
}

export function hasTranslation(value: string): boolean {
  const exact = EXACT[value];
  if (exact !== undefined) return exact !== "";
  const normalized = value.replace(/\s+/g, " ").trim();
  const normalizedExact = EXACT[normalized];
  if (normalizedExact !== undefined) return normalizedExact !== "";
  if (DYNAMIC_RULES.some(([pattern]) => pattern.test(value))) return true;
  if (RULES.some(([pattern]) => pattern.test(value))) return true;
  if (value.includes("；")) {
    const parts = value.split("；").map((part) => part.trim()).filter(Boolean);
    return parts.length > 1 && parts.some((part) => hasTranslation(part));
  }
  return false;
}

/**
 * Translate copy that never reaches the DOM, e.g. native `confirm` / `alert`
 * dialogs. The DOM translator cannot intercept those, so callers must run the
 * text through this helper before showing it.
 */
export function uiText(value: string): string {
  if (typeof window === "undefined") return value;
  let lang = "";
  try {
    lang = window.localStorage.getItem("stotp-lang") || "";
  } catch {
    lang = "";
  }
  if (lang !== "zh" && lang !== "en") {
    lang = (window.navigator.language || "zh").toLowerCase().startsWith("zh") ? "zh" : "en";
  }
  return lang === "en" ? translateText(value) : value;
}
